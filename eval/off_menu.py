"""FROZEN (Phase 19 tier map, training/README.md): vacuous for the champion by design.
Bug fixes and evidence readers only; no new search.

Off-menu action diagnostics — behaviour outside the FSM option menu.

Task 18.3 (tasks/phase-18.md; audits/audit-phase-18-planning.md §3.2) builds the
byte-grounded gauge of
impostor behaviour that lies OUTSIDE the FSM option menu. At each recorded
impostor decision the agent-visible packet + episodic memory is reconstructed
offline, the oracle's :func:`~agents.tactical.learned.forward.enumerate_options`
menu is materialised for that exact packet, and the recorded action's intent is
tested for membership in the menu — yielding an *off-menu RATE* over a recording
and a per-decision census of WHAT kind of novelty appeared.

Honest scoping (audits/audit-phase-18-planning.md §3.2, the corrected off-menu
finding) — carried in the module docstring AND in every report's ``scope_note``
field:

* The **menu-bounded champion is on-menu by construction**: it can only emit an
  action the menu offered, so its off-menu rate is **0 always**. The instrument
  is therefore VACUOUS for the champion and meaningful only for **free-policy**
  recordings (Tasks 18.22 / 18.24) that can step outside the menu.
* **FSM-generated bytes are the all-on-menu fixture.** The committed replay sets
  were recorded by the scripted FSM, whose emitted action space is a strict
  subset of the menu (the menu is a structural superset of the ``decide()``
  ladder), so this instrument reads rate 0 on every committed set — the fixture
  that proves the gauge is calibrated and does not false-positive.
* It is the **emergence gauge** for behaviour classes the FSM menu cannot reach
  (e.g. an impostor that reports, calls an emergency meeting, or moves to a room
  no option offered) and a **Tier-B pre-registration input**: Task 18.4 quotes
  the committed baseline cells (the ``impostor_decisions`` denominator and the
  all-zero off-menu counters) this task pins.
* This is **NOT** the training harness's anchor cross-entropy
  (``training/bakeoff/harness.py``). Anchor-CE is a rollout-time, distributional
  quantity (how far a learner's action *distribution* drifts from the FSM's);
  the off-menu rate is an offline, per-recorded-decision *membership* test. Do
  not conflate the two.

The reconstruction MIRRORS :func:`eval.funnel._walk_game_vj` (which itself
mirrors ``api/replay_loader.py`` — a mirrored local walk with full state-hash
verification is the established ``eval`` pattern): the game is re-seeded and the
recorded action stream is replayed through :func:`engine.tick.advance_tick` with
the SAME fail-loud verification — per-tick ``state_hash``, each meeting's
``state_hash_before`` / ``state_hash_after``, a MEETING tick with no meeting row,
a MEETING tick with no ``MeetingTriggeredEvent``, and a living impostor with no
recorded action all raise :class:`OffMenuReconstructionError`. The one deliberate
economy over ``_walk_game_vj``: only IMPOSTOR agents are instantiated, so only
living-impostor pre-advance packets are ingested and the post-meeting absorb fold
(the same ``extract_belief_evidence`` + ``derive_reported_testimony`` fan-out the
orchestrator runs — it writes episodic content too: ``provenance="reported"``
testimony rows and the meeting-boundary marker, ``agents/memory/store.py``) runs
for living impostors only. Skipping the CREW agents is byte-faithful for the
impostor menu because ``build_packet`` is a pure function of
``(world_state, agent_id, engine_events)`` with no cross-agent coupling, agent
memories are per-agent and independent, and
:func:`~agents.tactical.learned.forward.enumerate_options` reads ONLY the
impostor's own memory — so a skipped crew agent can never change an impostor
menu. The impostors' own feeding is NOT elided anywhere: every packet ingest and
every meeting absorb an impostor received live is replayed, so the episodic
store the menu is materialised from is the production one. The trajectory itself
is driven by the RECORDED actions, so the hashes reconstruct identically
regardless.

Membership + classification:

* An impostor's recorded engine :class:`~engine.actions.Action` is **on-menu**
  iff it equals ``translate_action_intent(option.intent)`` for some menu option
  (the sanctioned :func:`~orchestrator.boundary.translate_action_intent` bridge
  from the menu's :class:`~observation.action_intent.ActionIntent` plane onto the
  recorded ``Action`` plane; compared on ``model_dump(mode="python")`` — the
  version-agnostic value plane).
* Off-menu decisions are classified on the intent-KIND plane (the engine action
  ``type`` string: ``move`` / ``kill`` / ``vent`` / ``do_task`` / ``sabotage`` /
  ``wait`` / ``report`` / ``emergency`` / ``repair_sabotage``), NOT the finer
  ``OptionKind`` (which maps many-to-one onto intent kinds — ``stalk_toward`` /
  ``cover_move`` / ``reposition`` all emit ``move``, ``vent_exit`` / ``cover_vent``
  both emit ``vent``, ``kill_now`` emits ``kill``). So the classification plane is
  the intent kind, not the OptionKind:
  * **off-menu-by-kind** — the recorded action ``type`` appears in NO menu option
    (a kind the menu lacks, e.g. ``report``);
  * **off-menu-by-target** — the ``type`` appears in the menu but no option
    matches the full payload (a menu kind at a target the menu would not offer,
    e.g. ``move`` to a room no option offered).

JSON report schema (``OffMenuActionReport.model_dump()``) — STABLE::

    {
      "replay_set_dir": str,
      "num_players": int, "num_impostors": int, "tasks_per_crewmate": int,
      "games_total": int,
      "impostor_decisions": int,          # N: the denominator (18.4 quotes this)
      "on_menu_total": int,
      "off_menu_total": int,
      "off_menu_rate": float | null,      # off_menu_total / N; null iff N == 0
      "off_menu_by_kind": int,            # recorded type absent from the menu
      "off_menu_by_target": int,          # type present, full payload not offered
      "scope_note": str,                  # the honest-scoping statement above
      "off_menu_decisions": [ OffMenuDecisionRow, ... ]   # off-menu rows ONLY
    }

    OffMenuDecisionRow::
    {
      "seed": int, "tick": int, "actor": str,
      "recorded_action_type": str,        # engine action type of the deviation
      "recorded_action_payload": {..},    # its full payload (identifies target)
      "classification": "off_menu_by_kind" | "off_menu_by_target",
      "menu_intent_kinds": [str, ...],    # sorted unique intent kinds offered
      "menu_option_count": int            # options in the menu at that decision
    }

Pure + offline: no network, no ``AILIBI_*`` env, no LLM. The public surface
(stable — downstream tasks import these): :func:`compute_off_menu_report`,
:class:`OffMenuActionReport`, :class:`OffMenuDecisionRow`.
"""

