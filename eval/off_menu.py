@dataclass(frozen=True)
class _Decision:
    """One scored impostor decision: the membership verdict + its menu context."""

    seed: int
    tick: int
    actor: PlayerId
    on_menu: bool
    # ``None`` iff ``on_menu`` — off-menu decisions carry the intent-kind-plane
    # classification (by-kind vs by-target).
    classification: _Classification | None
    recorded_action_type: str
    recorded_action_payload: Mapping[str, Any]
    menu_intent_kinds: tuple[str, ...]
    menu_option_count: int


# --------------------------------------------------------------------------- #
# Report models                                                                #
# --------------------------------------------------------------------------- #


class OffMenuDecisionRow(BaseModel):
    """One off-menu impostor decision, identified for downstream reading.

    Emitted ONLY for off-menu decisions (the on-menu majority is summarised by
    the aggregate counters, never enumerated). The ``(seed, tick, actor)`` triple
    identifies the exact recorded decision; ``recorded_action_type`` +
    ``recorded_action_payload`` name the deviation; ``classification`` says WHAT
    kind of novelty (by-kind vs by-target) so Task 18.27 can read the emergence;
    ``menu_intent_kinds`` + ``menu_option_count`` give the menu context the
    deviation stepped outside of.
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    seed: int
    tick: int
    actor: PlayerId
    recorded_action_type: str
    recorded_action_payload: Mapping[str, Any]
    classification: _Classification
    menu_intent_kinds: tuple[str, ...]
    menu_option_count: int


class OffMenuActionReport(BaseModel):
    """The off-menu diagnostics over one replay set (frozen value object).

    ``off_menu_rate`` is ``None`` (not ``0.0``) when there are no impostor
    decisions to measure, mirroring the ``eval`` empty-denominator convention.
    On any FSM-generated (committed) set every off-menu counter is 0 and
    ``off_menu_decisions`` is empty — the all-on-menu fixture (see the module
    docstring and ``scope_note``).
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    replay_set_dir: str
    num_players: int
    num_impostors: int
    tasks_per_crewmate: int
    games_total: int
    impostor_decisions: int
    on_menu_total: int
    off_menu_total: int
    off_menu_rate: float | None
    off_menu_by_kind: int
    off_menu_by_target: int
    scope_note: str
    off_menu_decisions: tuple[OffMenuDecisionRow, ...]


# --------------------------------------------------------------------------- #
# Membership test + per-decision classification                                #
# --------------------------------------------------------------------------- #


def _classify_decision(
    seed: int,
    tick: int,
    actor: PlayerId,
    recorded_action: Action,
    menu: tuple[ImpostorOption, ...],
    world_state: WorldState | None = None,
) -> _Decision:
    """Test one recorded impostor action for menu membership and classify it.

    Membership is tested on the recorded ``Action`` plane: each menu option's
    :class:`~observation.action_intent.ActionIntent` is translated onto that
    plane via :func:`~orchestrator.boundary.translate_action_intent` and compared
    on ``model_dump(mode="python")`` (a version-agnostic value comparison immune
    to any pydantic ``__eq__`` nuance across the two parallel model families).

    Classification is on the intent-KIND plane — the engine action ``type`` — so
    the ``OptionKind`` many-to-one collapse never enters (see module docstring):
    ``off_menu_by_kind`` when the recorded type is offered by NO option,
    ``off_menu_by_target`` when the type is offered but no option matches the full
    payload.
    """

    recorded_dump = recorded_action.model_dump(mode="python")
    menu_dumps = [
        translate_action_intent(option.intent, world_state=world_state).model_dump(
            mode="python"
        )
        for option in menu
    ]
    on_menu = recorded_dump in menu_dumps

    menu_types = {option.intent.type for option in menu}
    classification: _Classification | None
    if on_menu:
        classification = None
    elif recorded_action.type not in menu_types:
        classification = "off_menu_by_kind"
    else:
        classification = "off_menu_by_target"

    payload = recorded_dump.get("payload") or {}
    return _Decision(
        seed=seed,
        tick=tick,
        actor=actor,
        on_menu=on_menu,
        classification=classification,
        recorded_action_type=recorded_action.type,
        recorded_action_payload=payload,
        menu_intent_kinds=tuple(sorted(menu_types)),
        menu_option_count=len(menu),
    )


# --------------------------------------------------------------------------- #
# The reconstruction walk (impostor-menu-faithful, crew ingestion elided)      #
# --------------------------------------------------------------------------- #


def _walk_game(
    replay_path: Path,
    *,
    seed: int,
    num_players: int,
    num_impostors: int,
    tasks_per_crewmate: int,
    roles: Mapping[PlayerId, Role],
    game_map: Map,
) -> list[_Decision]:
    """Re-seed + replay one game, scoring every living-impostor PLAY decision.

    Mirrors :func:`eval.funnel._walk_game_vj`'s engine walk + hash verification,
    its ``last_events`` threading across meetings, and its post-meeting absorb
    fold, but instantiates only IMPOSTOR agents — crew agents can never change an
    impostor menu (see the module docstring), while every ingest/absorb an
    impostor received live IS replayed. At each PLAY-phase tick, for each living
    impostor, the pre-advance packet is ingested (exactly as
    ``TacticalAgent.decide`` does before it runs the policy — so the oracle never
    sees empty memory) and the menu is materialised for that packet; the
    impostor's recorded action for that tick is tested for membership.
    """

    game_id = f"headless-seed-{seed}"
    entries = read_all_entries(replay_path)
    require_legacy_observations(entries, consumer="off-menu")
    tick_entries = [e for e in entries if isinstance(e, ReplayEntry)]
    meeting_by_tick: dict[int, MeetingReplayEntry] = {
        e.tick: e for e in entries if isinstance(e, MeetingReplayEntry)
    }

    state = seed_initial_state(
        seed=seed,
        game_map=game_map,
        num_players=num_players,
        num_impostors=num_impostors,
        tasks_per_crewmate=tasks_per_crewmate,
    )
    impostor_ids = tuple(
        sorted(pid for pid, role in roles.items() if role == "IMPOSTOR")
    )
    factory = build_default_agent_factory()
    agents: dict[PlayerId, TacticalAgent] = {}
    for pid in impostor_ids:
        agent = factory(pid, roles[pid])
        if not isinstance(agent, TacticalAgent):  # pragma: no cover - factory pin
            raise TypeError(
                "build_default_agent_factory returned a non-TacticalAgent; the "
                "memory-augmented walk cannot reconstruct the impostor menu "
                "without the production agent memory"
            )
        agents[pid] = agent

    public_map = public_map_from_engine_map(game_map)
    decisions: list[_Decision] = []
    audit_dir = tempfile.TemporaryDirectory(prefix="ailibi-off-menu-")
    service = ObservationService(
        game_map=game_map, audit_log_path=Path(audit_dir.name) / "audit.jsonl"
    )
    last_events: tuple[EngineEvent, ...] = ()

    try:
        for entry in tick_entries:
            # Score the PLAY-phase decision BEFORE advancing (the packet the
            # impostor decided from is the pre-advance packet of that tick). Every
            # ReplayEntry tick is a PLAY tick — meetings resolve inline within the
            # triggering tick below — but the guard keeps the contract explicit.
            if state.phase == "PLAY":
                recorded_by_actor = {raw["actor"]: raw for raw in entry.actions}
                for pid in impostor_ids:
                    if not state.players[pid].alive:
                        continue
                    packet = service.build_packet(
                        world_state=state, agent_id=pid, engine_events=last_events
                    )
                    # Ingest before enumerating, exactly as ``decide`` ingests
                    # before it runs the policy — the oracle raises on empty
                    # memory, so warm-up is mandatory, not optional.
                    ingest_packet(
                        packet=packet,
                        memory=agents[pid].memory.episodic,
                        beliefs=agents[pid].memory.beliefs,
                    )
                    raw_action = recorded_by_actor.get(pid)
                    if raw_action is None:
                        # Production records exactly one action per living player
                        # per tick; a missing one means the recording is partial
                        # or drifted, and skipping it would silently shrink the
                        # denominator ("no silent fallbacks").
                        raise OffMenuReconstructionError(
                            f"{game_id}: tick {entry.tick} carries no recorded "
                            f"action for living impostor {pid} — refusing to "
                            "silently under-measure"
                        )
                    menu = enumerate_options(packet, public_map, agents[pid].memory)
                    recorded_action = _ACTION_ADAPTER.validate_python(dict(raw_action))
                    decisions.append(
                        _classify_decision(
                            seed=seed,
                            tick=entry.tick,
                            actor=pid,
                            recorded_action=recorded_action,
                            menu=menu,
                            world_state=state,
                        )
                    )

            actions = [
                _ACTION_ADAPTER.validate_python(dict(raw)) for raw in entry.actions
            ]
            state, events = advance_tick(state, actions, game_map=game_map)
            actual = _state_hash(state)
            if actual != entry.state_hash:
                raise OffMenuReconstructionError(
                    f"{game_id}: tick {entry.tick} reconstructed {actual!r} != "
                    f"recorded {entry.state_hash!r} (roster mismatch or engine "
                    "non-determinism)"
                )

            if state.phase == "GAME_OVER":
                break
            if state.phase != "MEETING":
                last_events = tuple(events)
                continue

            # --- Resolve the meeting inline so later ticks/hashes reconstruct. ---
            meeting_entry = meeting_by_tick.get(entry.tick)
            if meeting_entry is None:
                raise OffMenuReconstructionError(
                    f"{game_id}: tick {entry.tick} entered MEETING but the replay "
                    "carries no meeting row for that tick (partial recording or "
                    "drifted meeting tick) — refusing to silently under-measure"
                )
            if meeting_entry.state_hash_before != actual:
                raise OffMenuReconstructionError(
                    f"{game_id}: meeting at tick {entry.tick} recorded "
                    f"state_hash_before {meeting_entry.state_hash_before!r} != "
                    f"reconstructed pre-meeting state {actual!r}"
                )

            trigger_event: MeetingTriggeredEvent | None = None
            for event in events:
                if isinstance(event, MeetingTriggeredEvent):
                    trigger_event = event
            if trigger_event is None:
                raise OffMenuReconstructionError(
                    f"{game_id}: tick {entry.tick} entered MEETING without a "
                    "MeetingTriggeredEvent (engine invariant violation)"
                )
            body_id = (
                trigger_event.body_id if trigger_event.trigger == "report" else None
            )

            result = MeetingResult(
                meeting_id=meeting_entry.meeting_id,
                triggered_by=meeting_entry.triggered_by,
                trigger_tick=meeting_entry.tick,
                outcome=meeting_entry.outcome,
                ejected_player_id=meeting_entry.ejected_player_id,
                ballots=meeting_entry.ballots,
                contradictions=meeting_entry.contradictions,
                transcript=meeting_entry.transcript,
            )
            pre_meeting_events = tuple(events)
            state, post_events = apply_meeting_result(
                state, result, game_map=game_map, triggering_body_id=body_id
            )
            after = _state_hash(state)
            if after != meeting_entry.state_hash_after:
                raise OffMenuReconstructionError(
                    f"{game_id}: meeting at tick {entry.tick} reconstructed "
                    f"{after!r} != recorded {meeting_entry.state_hash_after!r}"
                )
            # The post-meeting absorb fold, mirroring ``_walk_game_vj`` /
            # ``orchestrator.game._absorb_meeting_beliefs`` for the IMPOSTOR
            # agents (crew agents are not instantiated — module docstring): one
            # evidence reduction + one absorb per impostor still alive in the
            # post-meeting state, sorted. ``absorb_reported_testimony`` writes
            # EPISODIC content (``provenance="reported"`` rows + the boundary
            # marker at the first post-meeting tick), and ``enumerate_options``
            # reads the episodic store — eliding this fold would hand the oracle
            # a memory the live impostor never had.
            evidence = extract_belief_evidence(
                result, trigger_kind=trigger_event.trigger
            )
            statements = derive_reported_testimony(result)
            for pid in impostor_ids:
                if not state.players[pid].alive:
                    continue
                agents[pid].absorb_meeting_evidence(
                    accused=evidence.accused,
                    corroborated=evidence.corroborated,
                    contradicted=evidence.contradicted,
                )
                agents[pid].absorb_reported_testimony(statements=statements)

            last_events = pre_meeting_events + tuple(post_events)
            if state.phase == "GAME_OVER":
                break
    finally:
        audit_dir.cleanup()

    return decisions


