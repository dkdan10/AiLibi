_Classification = Literal["off_menu_by_kind", "off_menu_by_target"]


class OffMenuReconstructionError(RuntimeError):
    """A recorded state hash did not reconstruct — the set is corrupt/drifted.

    Raised during the walk when a per-tick ``state_hash``, a meeting's
    ``state_hash_before`` / ``state_hash_after``, or a required engine invariant
    (a MEETING tick's meeting row / ``MeetingTriggeredEvent``) disagrees with the
    reconstruction, so a drifted or corrupted replay set fails loud rather than
    silently mis-measuring the off-menu rate (AGENTS.md "no silent fallbacks").
    """


