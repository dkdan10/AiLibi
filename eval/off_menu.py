def compute_off_menu_report(sample_dir: Path) -> OffMenuActionReport:
    """Fold a replay set's committed bytes into the off-menu diagnostics.

    Re-seeds every game from the set's roster (``roster.json`` via
    :func:`eval.validity.resolve_roster_knobs`; the flat 4p1i default otherwise),
    walks each recorded action stream through the engine with per-tick +
    per-meeting state-hash verification (:func:`_walk_game`), materialises the
    oracle menu at every living-impostor PLAY decision, and folds the membership
    verdicts into the off-menu census. Runs on any replay-set directory and both
    roster presets. Pure and offline.

    Mirrors :func:`eval.funnel.compute_pooling_funnel` for the entry-point shape
    (a single ``sample_dir: Path`` in, a frozen report out).
    """

    num_players, num_impostors, tasks_per_crewmate = resolve_roster_knobs(sample_dir)
    game_map = load_canonical_map()
    per_seed_roles = roles_by_seed(
        sample_dir,
        num_players=num_players,
        num_impostors=num_impostors,
        tasks_per_crewmate=tasks_per_crewmate,
        game_map=game_map,
    )
    seeds = seeds_on_disk(sample_dir)
    if not seeds:
        raise ValueError(f"no replay-seed-*.jsonl found under {sample_dir}")

    decisions: list[_Decision] = []
    for seed in seeds:
        decisions.extend(
            _walk_game(
                sample_dir / f"replay-seed-{seed}.jsonl",
                seed=seed,
                num_players=num_players,
                num_impostors=num_impostors,
                tasks_per_crewmate=tasks_per_crewmate,
                roles=per_seed_roles[seed],
                game_map=game_map,
            )
        )

    n = len(decisions)
    off_menu = [d for d in decisions if not d.on_menu]
    off_menu_by_kind = sum(
        1 for d in off_menu if d.classification == "off_menu_by_kind"
    )
    off_menu_by_target = sum(
        1 for d in off_menu if d.classification == "off_menu_by_target"
    )
    rows = tuple(
        OffMenuDecisionRow(
            seed=d.seed,
            tick=d.tick,
            actor=d.actor,
            recorded_action_type=d.recorded_action_type,
            recorded_action_payload=d.recorded_action_payload,
            # ``off_menu`` decisions always carry a classification (never None).
            classification=_require_classification(d),
            menu_intent_kinds=d.menu_intent_kinds,
            menu_option_count=d.menu_option_count,
        )
        for d in off_menu
    )
    return OffMenuActionReport(
        replay_set_dir=str(sample_dir),
        num_players=num_players,
        num_impostors=num_impostors,
        tasks_per_crewmate=tasks_per_crewmate,
        games_total=len(seeds),
        impostor_decisions=n,
        on_menu_total=n - len(off_menu),
        off_menu_total=len(off_menu),
        off_menu_rate=(len(off_menu) / n if n else None),
        off_menu_by_kind=off_menu_by_kind,
        off_menu_by_target=off_menu_by_target,
        scope_note=_SCOPE_NOTE,
        off_menu_decisions=rows,
    )


def _require_classification(decision: _Decision) -> _Classification:
    """Narrow an off-menu decision's classification for the typed row.

    An off-menu decision ALWAYS carries a classification (only on-menu decisions
    hold ``None``); this fails loud rather than silently coercing, so a logic
    error surfaces instead of a mislabelled row (AGENTS.md "no silent fallbacks").
    """

    if decision.classification is None:  # pragma: no cover - invariant guard
        raise OffMenuReconstructionError(
            f"off-menu decision at seed {decision.seed} tick {decision.tick} "
            f"actor {decision.actor} has no classification (logic error)"
        )
    return decision.classification


